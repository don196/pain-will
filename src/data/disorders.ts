export const WILL_CRIT = 3;
export function disDesc(k, f) {
  const P = DISP[k],
    i = f - 1;
  switch (k) {
    case 'fear':
      return `−${P.pen[i]} к атакам. Критический провал атаки — «Тряска» на ${P.shake} своих хода: промах из дальнобойного оружия тратит 2 снаряда вместо 1`;
    case 'distrust':
      return f === 1
        ? `Бафф прямо на персонажа — у накладывающего −${P.pen} к броску. Бафф по области — отдельная проверка накладывающего против базовой защиты + той же характеристики персонажа (Интуиции или Харизмы); провал — на него бафф не действует`
        : `Всё, что у Недоверия; провал баффа на него — прямого или отдельной проверки по области — внеочередная базовая атака по ближайшему союзнику без ОД`;
    case 'sad':
      return `−${P.sp[i]} к ${STAT_DAT[P.stat]}. Провал или критический провал атаки или способности (не защиты) — именно её нельзя повторить ${P.ban[i] === 1 ? 'в этот и следующий ход' : `следующие ${P.ban[i]} хода`}; запрет один, новый заменяет старый`;
    case 'indec':
      return (
        `Критический успех атаки, способности или защиты перебрасывается, повторный бросок −${P.re[i]}` +
        (f === 2 ? '. Если повторный бросок не удался, ход завершается' : '')
      );
    case 'aggr':
      return (
        `−${P.pen[i]} к атакам. После промаха следующее действие — обычная атака оружием, если атаковать можно; иначе обязанность ждёт` +
        (f === 2 ? '. Цель такой атаки — случайный противник в досягаемости' : '')
      );
    case 'odd':
      return (
        `К каждому броску d20 — ещё d6: 1–4 → −${P.lo}, 5–6 → +${P.hi}` +
        (f === 2
          ? '. Плюс всё, что у Недоверия. На d6 1 или 6 цель меняется после броска: атака или дебафф противника — на союзника (нет — на другого противника), бафф союзника — на противника; по области — так же'
          : '')
      );
    case 'obsess':
      return (
        `${P.sp[i] ? `−${P.sp[i]} к ${STAT_DAT[P.stat]}. ` : ''}Если способность по области готова и в её области есть цель (для баффа — союзник, кроме себя; для атаки — противник), её надо применить первым действием хода` +
        (f === 2
          ? `. Атакующие способности по области задевают и союзников${P.fanR ? ` в радиусе ${P.fanR} от себя` : ''}${P.fanDmg < 1 ? ` (${P.fanDmg === 0.5 ? 'половина урона' : 'урон ×' + fmtN(P.fanDmg)})` : ''}`
          : '')
      );
    case 'cruel':
      return f === 1
        ? `−${P.pen[0]} к атакам и способностям по цели без раны (нет открытой раны и кровотечения)`
        : `Если в досягаемости есть противник с открытой раной или кровотечением, атаковать можно только таких; по остальным −${P.pen[1]} к атакам и способностям. Убив противника своим ударом, совершает жестокое добивание: ход заканчивается, союзники в радиусе ${P.r} теряют по ${P.will} Воле`;
    case 'shame':
      return (
        `Заклинания с освещённого гекса: −${P.pen[i]} к броску; из темноты — без штрафа` +
        (f === 2
          ? '. Критический провал заклинания (натуральная 1) — магическая отдача: заклинание не срабатывает, Хельга получает 3 урона сквозь броню'
          : '')
      );
    case 'guilt':
      return (
        `−${P.sp[i]} к ${STAT_DAT[P.stat]}. Если союзник в пределах ${P.r} клеток получил рану или упал, в следующий ход персонаж обязан первым делом дойти до него (если может) и по возможности перевязать, и закончить ход рядом` +
        (f === 2
          ? '. Атака по союзнику рядом с ним переходит на него, если атакующий может его достать; активной защиты против неё нет'
          : '')
      );
  }
  return '';
}
