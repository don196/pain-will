export let modalOnClose = null;

export function openModal(html, mount?, opt: Opts = {}) {
  modalOnClose = opt.onClose || null;
  $('#mbox').classList.toggle('wide', !!opt.wide);
  $('#mbox').innerHTML = `<button type="button" class="x" id="mClose">Закрыть</button>` + html;
  $('#modal').hidden = false;
  $('#mClose').onclick = closeModal;
  $('#mClose').focus();
  if (mount) mount();
}

export function closeModal() {
  $('#modal').hidden = true;
  if (modalOnClose) {
    const f = modalOnClose;
    modalOnClose = null;
    f();
  }
}

